from fractions import Fraction
import json
# Integer homogeneous coefficient arithmetic; no computer algebra package.
def add(a,b):
 c=a.copy()
 for k,v in b.items():
  c[k]=c.get(k,0)+v
  if c[k]==0:del c[k]
 return c
def scale(a,c):return {k:c*v for k,v in a.items() if c*v}
def mul(a,b):
 c={}
 for (i,j),v in a.items():
  for (k,l),w in b.items():c[(i+k,j+l)]=c.get((i+k,j+l),0)+v*w
 return {k:v for k,v in c.items() if v}
u={(1,0):1};v={(0,1):1}
q=add(mul(u,u),scale(mul(v,v),-1))
x=mul(v,q);y=mul(u,q);z=mul(mul(v,v),v)
res=add(mul(mul(y,y),z),scale(mul(mul(x,x),add(x,z)),-1))
assert res=={}
# O(D) -> O on the normalization is multiplication by f=u-2.
fp=Fraction(1)-2;fq=Fraction(-1)-2;lam=fp/fq
assert lam==Fraction(1,3)
# f has a simple zero at2 and a simple pole at infinity.
orders={'u=2':1,'u=infinity':-1,'u=1':0,'u=-1':0}
# Its gluing ratio has3-adic valuation-1; its m-th power has-m.
assert lam.numerator==1 and lam.denominator==3
# In R={(a,b):a(0)=b(0)}, M_l={(f,g):f(0)=l*g(0)}
# is generated by(l,1); the componentwise product sends the two
# generators to(l*m,1), so the tensor transport is an isomorphism.
print(json.dumps({'homogeneous_cubic_residual':res,'coordinates':{'x':str(x),'y':str(y),'z':str(z)},'node_values_f':[str(fp),str(fq)],'gluing_ratio':str(lam),'divisor_orders':orders,'v3_lambda':-1,'v3_lambda_power':'-m, for every positive integer m','normalization_ring_map':'x=u^2-1; y=u*(u^2-1); inverse u=y/x off the node','bundle_trivialization_map':'s -> (u-2)*nu^*s','local_generator_map':'(a,b) -> (lambda*a,b); inverse (f,g) -> (lambda^-1*f,g)'},indent=2))
