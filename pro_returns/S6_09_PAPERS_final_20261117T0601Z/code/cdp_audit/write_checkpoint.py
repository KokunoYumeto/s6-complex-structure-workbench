"""Write reviewable correction blocks and an honest current audit snapshot."""
from pathlib import Path
import json
root=Path(__file__).resolve().parents[3]
out=root/'deliverables/work/cdp_audit'

def statement_block(name):
    s=(out/'extracted'/name).read_text()
    return s[:s.index('\\end{proof}')+len('\\end{proof}')]

a1=statement_block('CDP_A_1_1.tex')
a1=a1.replace('Under the two vanishings in Lead 1,',
              'Under the explicit hypotheses $H^0(S,N^*\\otimes A)=0$ and $H^0(S,Q\\otimes A)=0$,')
a2=statement_block('CDP_A_2_6.tex')
old='The differential image in $\\C\\{t\\}\\,dt$ is $t^4\\C\\{t\\}\\,dt$.'
new='The $B$-module generated by the differential image, where $B=\\C\\{t\\}$, is $t^4B\\,dt$.'
assert old in a2
a2=a2.replace(old,new)
intro=r'''% Corrected proof blocks only; this is not the Paper II manuscript.
% Exact source IDs and existing labels are preserved.
% Checker: GPT-6 Astra (OpenAI, ChatGPT Pro mode), effort Pro, writing run,
% 17 November 2026 UTC.
% For A.1.1, S is a reduced Cartier hypersurface of a smooth complex
% manifold Y; N^*=I_S/I_S^2, V=Omega_Y^1|_S,
% T=tors(Omega_S^1), Q=Omega_S^1/T, and A is a line bundle on S.
% These definitions must be stated in prose before the block in the paper.
'''
(out/'corrected_A1_1_A2_6_full_proofs.tex').write_text(intro+'\n'+a1+'\n\n'+a2+'\n')

c4g=statement_block('CDP_C4g.tex')
old=r'''These threefolds have $H^2(Y,\Z)=0$. Pulling back any
ambient line to $\mathrm dP_6$ gives zero integral first
Chern class. The exponential sequence there, with
$H^1(\mathrm dP_6,\OO)=0$, makes that line trivial.
This applies to $K_Y^{-1}\otimes L$ as well as to $L$.
Serre duality on $\mathrm dP_6$ proves (C.TEST.1).
The last assertion about ambient $H^2$ follows from C4f
through the zero Picard pullback at this fixed fibre.
It does not require surjectivity of the global
normalization map for every twist; C5b computes the
actual exceptions to that surjectivity in the original
family.'''
new=r'''For every member in question, $H^2(Y,\Z)$ is a finite
group. For the original affine family this follows from E19:
the universal coefficient sequence gives
\[
 H^2(Y,\Z)\simeq\operatorname{Ext}^1(H_1(Y,\Z),\Z)
 \simeq\Z/d\Z,\qquad d=|p|,
\]
because $H_2(Y,\Z)$ is torsion. In the two other families
the integral homology is that of the six-sphere. In
particular every ambient first Chern class is torsion.
The group $H^2(\mathrm dP_6,\Z)$ is free, so its pullback
to $\mathrm dP_6$ is zero. The exponential sequence there,
together with $H^1(\mathrm dP_6,\OO)=0$, shows that the
pulled-back line bundle is trivial. This applies to both
$L$ and $K_Y^{-1}\otimes L$, and Serre duality on
$\mathrm dP_6$ proves (C.TEST.1).

All these threefolds have $b_1=b_2=b_3=0$: use E19 for
every original affine member, and the integral homology
of the six-sphere for the other two families. Any full
fibre is a nonzero effective Cartier divisor. Statement
C.1.3 therefore gives
\[
 h^2(Y,T_Y\otimes L)\geq 1
 \qquad\text{for every }L\in\Pic(Y).
\]
This argument applies equally when $d>1$ and the integral
cohomology has nonzero torsion. It requires no surjectivity
of the global normalization cohomology map. Indeed C5b
computes the actual exceptions to that surjectivity in
the original family.'''
assert old in c4g
c4g=c4g.replace(old,new)
(out/'corrected_C4g_full_proof.tex').write_text(intro+'\n'+c4g+'\n')

rows=json.loads((out/'result_audit.json').read_text())
done=[r for r in rows if r.get('own_check')]
pending=[r['source_id'] for r in rows if not r.get('own_check')]
text=['# Current CDP audit status','',
      'Checkpoint: 17 November 2026 UTC. Checker: GPT-6 Astra (OpenAI, ChatGPT Pro mode), effort Pro, writing run. Separately identified team-reader events retain their own exact locators.','',
      f'{len(done)} of {len(rows)} final-result rows have an explicit current-run check record. This count measures recorded work, not complete certification of their dependency chains. The outcome and outstanding dependencies are stated separately in each row. All 239 statements have source locators and full extracted statement/proof blocks; all 46 working-edition labels and five INV-E rows also have separate inventories.','',
      f"The current per-row records supersede earlier pending-source or pending-program notes in the chronological AUDIT_LOG.md. The {len(json.loads((out/'references_verified.json').read_text()))} opened-reference records distinguish exact statement checks from full proof reading, and distinguish genuine retained PDFs from web-only openings.",'',
      'No Paper II manuscript has been assembled.','',
      '## Current result-level findings','']
for r in done:
    text += [f"### {r['source_id']}",'',r['own_check'],'',f"**Outcome:** {r.get('check_outcome','')}",'']
    for key,label in [('depends_on','Dependencies or remaining checks'),('credit_checks','Literature/credit'),('remarks','Details')]:
        if r.get(key): text += [f"**{label}:** {r[key]}",'']
text += ['## Rows without a current-run proof-check record','',', '.join(pending), '']
(out/'AUDIT_STATUS.md').write_text('\n'.join(text))
print('Wrote corrected full proof blocks and',len(done),'row checkpoint')
