"""Assemble the authored proof fragments in the exact order of prompt Parts.

Original agent-owned fragments remain intact.  The generated parts are under
build/ordered and are the inputs of the deliverable manuscript.  Every tagged
statement occurs exactly once; the manifest records its source and placement.
"""
from pathlib import Path
import json
import re

root=Path(__file__).resolve().parents[1]
out=root/'build'/'ordered'
out.mkdir(parents=True,exist_ok=True)
titles={
 'A':('The conormal step in full generality',{
  'A.1':'Canonical cotangent kernels and ordinary crossings',
  'A.2':'Inverse Jacobian ideals and conductor calculations',
  'A.3':'Full fibres and their multiplicities',
  'A.4':'The torsion-free cotangent assertion',
  'A.5':'Normalizations and persistent ambient sections'}),
 'B':('Counterexamples and necessary fibre defects',{
  'B.1':'The nodal test family and every gluing scalar',
  'B.2':'A compact counterexample to the ambient inference',
  'B.3':'Necessary singular fibres for positive Euler characteristic'}),
 'C':('The index, fibre geometry and a corrected vanishing theorem',{
  'C.1':'The tangent index and generic endpoint vanishing',
  'C.2':'Euler numbers and degenerate fibres',
  'C.3':'Possible smooth general fibres',
  'C.4':'Geometric vanishing criteria',
  'C.5':'The normalization quotient and every tangent twist'}),
 'D':('Monodromy and coherent restriction maps',{
  'D.1':'The corrected count, restriction and generic non-torsion statements',
  'D.2':'The trivial-monodromy question'}),
 'E':('Algebraic reduction and deformation stability',{
  'E.1':'Vertical divisors and algebraic dimension',
  'E.2':'Nonholomorphic reduction and the printed proof',
  'E.3':'Algebraic-dimension exclusions and Kuranishi germs',
  'E.4':'Stability of the torus pencil and its exact rank loci'})}

special={
 'B1':'B.1','B2':'B.2','B3':'B.2',
 'C2a':'C.2','C2b':'C.2','C2c':'C.2','C2d':'C.2',
 'C4a':'C.4','C4b':'B.3','C4c':'C.4','C4d':'C.4','C4e':'B.3','C4f':'C.4','C4g':'B.3',
 'C5a':'C.5','C5b':'C.5','C5c':'C.5',
 'E1':'E.1','E2':'E.2','E3':'E.3','E4':'E.4','E5':'E.4',
 'E6':'E.4','E7':'E.4','E8':'E.4','E9':'E.3','E10':'E.4',
 'E11':'E.3','E12':'E.2','E13':'E.3','E14':'E.3',
 'E15':'E.3','E16':'E.4','E17':'E.2','E18':'E.4','E19':'E.3'}
pat=re.compile(r'\\begin\{statement\}\{([^}]*)\}\{[^}]*\}\{[^}]*\}|'
 r'\\begin\{(proposition|theorem|corollary|lemma|example|remark)\}\[([A-E]\.\d+(?:\.(?:\d+|[A-Z]+))*);\s*([^\]]+)\]')
groups={key:[] for _,subs in titles.values() for key in subs}
manifest=[]
seen=set()
for path in sorted((root/'sections').glob('part_*.tex')):
    text=path.read_text()
    # Nested proof fragments are assembled independently, exactly once.
    text=re.sub(r'(?m)^\\input\{sections/part_[^}]+\}\s*\n?','',text)
    # Prompt headings are supplied centrally, without changing proof text.
    text=re.sub(r'(?m)^\\(?:sub)*section\*?\{[^\n]*\}\s*\n?','',text)
    matches=list(pat.finditer(text))
    if not matches:
        continue
    prefix=text[:matches[0].start()].strip()
    for i,m in enumerate(matches):
        ident=m.group(1) or m.group(3)
        if ident in seen:
            raise RuntimeError('Duplicate statement '+ident)
        seen.add(ident)
        group=special.get(ident,'.'.join(ident.split('.')[:2]))
        if group not in groups:
            raise RuntimeError('Unplaced statement '+ident)
        end=matches[i+1].start() if i+1<len(matches) else len(text)
        block=text[m.start():end].strip()
        if m.group(2):
            env,status=m.group(2),m.group(4)
            opening=re.match(r'\\begin\{'+env+r'\}\[[^\]]+\]',block).group()
            block=block.replace(opening,'\\begin{idstatement}{'+ident+'}{'+status+'}',1)
            block=block.replace('\\end{'+env+'}','\\end{idstatement}',1)
        if i==0 and prefix:
            block=prefix+'\n\n'+block
        groups[group].append((ident,block,path.name))
        manifest.append({'id':ident,'part':group,'source':str(path.relative_to(root))})

def number_key(item):
    ident=item[0]
    # Within each requested item, follow the statement's explicit number.
    return tuple(int(x) for x in re.findall(r'\d+',ident))

for letter,(title,subs) in titles.items():
    content=['% Generated by code/assemble_manuscript.py; edit source fragments.\n',
             '\\section{'+letter+'. '+title+'}\n']
    for key,subtitle in subs.items():
        content.append('\\subsection{'+key+'. '+subtitle+'}\n')
        items=groups[key]
        # C2 places the general examples, then NC and local jet refinements.
        if key!='C.2':
            items=sorted(items,key=number_key)
        for ident,block,source in items:
            content.extend(['% '+ident+' from '+source+'\n',block+'\n\n'])
    (out/(letter+'.tex')).write_text('\n'.join(content))
(out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(f'Placed {len(seen)} statements in {len(groups)} requested items.')
for key,items in groups.items():
    print(key+': '+', '.join(x[0] for x in items))
