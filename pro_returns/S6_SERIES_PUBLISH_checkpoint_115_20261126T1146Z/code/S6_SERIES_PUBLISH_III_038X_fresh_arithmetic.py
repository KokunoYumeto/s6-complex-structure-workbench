#!/usr/bin/env python3
"""Exact finite arithmetic and local formulas for the still-closed 038X."""
from math import gcd
import sympy as s

delta = {m: 2*m % 24 for m in range(12)}
assert len(set(delta.values())) == 12
assert set(delta.values()) == set(range(0, 24, 2))
assert all(((delta[a]+delta[b]) % 24 == delta[(a+b) % 12])
           for a in range(12) for b in range(12))
assert all((delta[m]//2) % 12 == m for m in range(12))
print('delta:Z/12 -> Z/24:', delta)
print('Exact even image, inverse and all 144 addition pairs verified.')

elements = [(n, m) for n in range(24) for m in range(12)]
quotient = lambda v: (v[0]+2*v[1]) % 24
kernel = {v for v in elements if quotient(v) == 0}
relation = {(2*k % 24, -k % 12) for k in range(12)}
assert kernel == relation
assert {quotient(v) for v in elements} == set(range(24))
for a in elements:
    for b in elements:
        assert quotient(((a[0]+b[0]) % 24, (a[1]+b[1]) % 12)) == (quotient(a)+quotient(b)) % 24
print('Finite reduction of L verified on all 288 elements and 82944 pairs.')
print('Kernel generated by (2,-1):', sorted(kernel))
print('The fresh proof separately proves the full infinite-source kernel and inverse.')

units = [d for d in range(12) if gcd(d, 12) == 1]
for d in units:
    inverse = pow(d, -1, 12)
    assert (inverse*d) % 12 == 1
    assert (2*inverse*d) % 24 == 2
    assert 24 // gcd(2*d, 24) == 12
    print('J coefficient', d, 'inverse twist degree', inverse,
          'final coefficient', inverse*d % 12, 'stabilized class', 2*inverse*d % 24)

stable_pairs = [(5, 8), (6, 9), (7, 10), (8, 11)]
assert all(i < 2*n-1 for n, i in stable_pairs)
assert (-1)**(3*6) == (-1)**(6*6) == 1
print('Four strict suspension ranges:', [(i, 2*n-1) for n, i in stable_pairs])
print('Both block twist degrees are +1.')

t, y, c = s.symbols('t y c', positive=True)
h = c*(t-y)/(t*(1-t))
derivative = c*((t-y)**2+y*(1-y))/(t**2*(1-t)**2)
assert s.factor(s.diff(h, t)-derivative) == 0
assert s.simplify(s.diff(h, t).subs(t, y)-c/(y*(1-y))) == 0
print('Exact derivative of h and its value at the chosen interior coordinate verified.')

r, sigma = s.symbols('r sigma', positive=True)
real = (r**2-4*sigma**2)/(r**2+4*sigma**2)
imag_scale = 4*sigma/(r**2+4*sigma**2)
assert s.factor(real**2+imag_scale**2*r**2-1) == 0
assert s.limit(imag_scale.subs(sigma, 1), r, 0) == 1
print('Quaternion collapse has unit norm and derivative I at its centre.')
print('All exact checks passed; no canonical source or global table modified.')
