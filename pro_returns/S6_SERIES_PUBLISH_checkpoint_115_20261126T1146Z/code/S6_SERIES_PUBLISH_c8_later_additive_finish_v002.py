#!/usr/bin/env python3
"""Two readback clarifications and local publication records; no shared writes."""
from pathlib import Path
from hashlib import sha256
from datetime import datetime, timezone
import csv
import difflib

ROOT = Path(__file__).resolve().parents[1]
UNIT = ROOT / 'agents/continuation8_iii_integration/units/later/elliptic_additive_profiles.tex'
OUT = ROOT / 'agents/continuation8_iii_later'
TABLE = OUT / 'S6_SERIES_PUBLISH_III_additive_publication_defects.tsv'
old = UNIT.read_text()
assert sha256(old.encode()).hexdigest() == '681c08adc8fbf9b29ba1c271f8fd97c28389c8066e8a7b5323fc40df2130dcd9'
with TABLE.open(newline='') as stream:
    rows = list(csv.DictReader(stream, delimiter='\t'))
assert len(rows) == 104
fields = list(rows[0])
new = old
changes = [
    ('maps:src:D.2.18', 'D20',
     r'The outside degree-two group is generated by the functional dual to \(V\).',
     r'The outside cohomology group \(H^2(Q\setminus\mathring D;\mathbb Z)\)' + '\n' +
     r'is generated by the functional dual to \(V\).',
     'Name the precise integral cohomology group already computed in the preceding paragraph; retain the same dual functional and relative-cocycle extension map.'),
    ('maps:src:D.2.20', 'D23',
     'and has a smooth increasing inverse. Together with the\nangular isotopy with its endpoint adjustment it identifies the original cap with',
     'and has a smooth increasing inverse. Together with the angular isotopy,\nincluding its endpoint adjustment, it identifies the original cap with',
     'Clarify the sentence syntax while retaining the roof map, corrected isotopy, target and inverse.')
]
for sid, kind, before, after, reason in changes:
    assert new.count(before) == 1
    pos = new.index(before)
    rows.append(dict(change_id=f'c8-III-additive-{len(rows)+1:03}', type=kind,
                     statement_id=sid,
                     old_location='elliptic_additive_profiles.tex, final readback line ' + str(new[:pos].count('\n') + 1),
                     old_page='pending final page concordance',
                     new_location='elliptic_additive_profiles.tex, corresponding retained statement',
                     new_page='pending final build', old_text=before, new_text=after,
                     reason=reason,
                     review_status='whole unit and exact readback edit reviewed; root admission, final placement and rendered-page gates pending'))
    new = new.replace(before, after, 1)

# Heading insertions belong to the statement they introduce, not the
# preceding statement returned by the earlier position-only recorder.
rows[7]['statement_id'] = 'maps:src:D.2.20'
rows[8]['statement_id'] = 'maps:src:D.2.21'
for row in rows[:104]:
    row['review_status'] = 'whole repaired input, admitted comparison, exact diff and complete final unit read; root admission, global links/numbering/bibliography, final placement and rendered-page gates pending'
with TABLE.open('w', newline='') as stream:
    writer = csv.DictWriter(stream, fields, delimiter='\t', lineterminator='\n')
    writer.writeheader()
    writer.writerows(rows)
diff = ''.join(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                  fromfile='additive_v001', tofile='additive_v002'))
(OUT / 'S6_SERIES_PUBLISH_III_additive_publication_v002.diff').write_text(diff, newline='\n')
UNIT.write_text(new, newline='\n')

now = datetime.now(timezone.utc).isoformat()
eventfile = OUT / 'S6_SERIES_PUBLISH_III_additive_publication_CHECK_EVENTS.tsv'
eventfields = ['statement_id', 'date', 'who', 'type', 'outcome', 'event_id', 'phase',
               'source_file', 'source_row', 'source_event_type', 'evidence_group',
               'publish_input_file', 'publish_input_row', 'date_utc', 'where']
scopes = [
    ('02KR', 'maps:src:D.2.17', 'Original II and IV caps, all free regular logs, full primitive transfer maps, n=0 and n nonzero groups, and both simply connected signs with their oriented suspension framing remain.'),
    ('02KS', 'maps:src:D.2.18', 'Actual (3,0),(4,1) cusp periods, three embedded components, primitive fixed classes and nonzero cubic, original II/star caps, all log parameters, and the flag-threefold connected-sum type remain. Q300 numbers the same incidence definition before its use.'),
    ('02KV', 'maps:src:D.2.20', 'All six original additive configurations, every free regular log, the zero-vector Bezout case, complete rim and canonical maps, both simply connected signs and the explicit Engel model identification remain.'),
    ('02KW', 'maps:src:D.2.21', 'All five finite/original cap choices, every k>0 and r integer with gcd(n,m)=1, full boundary normals, the retained exterior cyclic class and its exact gluing cancellation, and the oriented classification remain.')
]
events = []
for i, (tag, sid, scope) in enumerate(scopes, 2):
    line = new[:new.index('\\label{' + sid + '}')].count('\n') + 1
    events.append(dict(statement_id=sid, date=now[:10],
        who='GPT-6 Astra Pro (OpenAI), ChatGPT Pro mode; numerical effort not separately exposed',
        type='used and rechecked in this run',
        outcome='Complete repaired proof read against its complete admitted original/receiving comparison; complete final unit read and exact local edits reviewed. All D01-D27 and actual source structure inspected. ' + scope + ' This is source-local publication rechecking; no new independent-proof or historical-computation credit. Root admission, actual final placement, global link/numbering/bibliography expansion and rendered pages remain separate.',
        event_id='publish:c8:III:' + tag + ':publication-unit', phase='continuation8-later-publication',
        source_file=str(UNIT.relative_to(ROOT)), source_row=str(line),
        source_event_type='used and rechecked in this run', evidence_group='publish:c8:III:later-unit-editing',
        publish_input_file=str(eventfile.relative_to(ROOT)), publish_input_row=str(i),
        date_utc=now, where='agents/continuation8_iii_later/S6_SERIES_PUBLISH_III_additive_publication_review.md'))
with eventfile.open('w', newline='') as stream:
    writer = csv.DictWriter(stream, eventfields, delimiter='\t', lineterminator='\n')
    writer.writeheader()
    writer.writerows(events)
print('UTC', now)
print('OUTPUT', len(new.splitlines()), sha256(new.encode()).hexdigest())
print('TWO_READBACK_EDITS', len(changes), 'LOCAL_DEFECT_ROWS', len(rows), 'LOCAL_EVENTS', len(events))
print('HEADING_OWNER_ROWS_CORRECTED', '008->02KV', '009->02KW')
print('NO_CANONICAL_OR_SHARED_WRITES; NO_NEW_INDEPENDENT_CHECK_CREDIT')
