#!/usr/bin/env python3
"""Prepare bounded occurrence-program appendix rows; never edit shared source."""
from pathlib import Path
from datetime import datetime, timezone
import csv
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'agents/continuation3_provenance'
data = json.loads((ROOT.parents[1] / 'tmp/c3_programs/programs160_metadata.json').read_text())
source = (ROOT / 'S6_SERIES_PUBLISH_II.tex').read_text()
table = source[source.index(r'\section*{Programs}'):source.index(r'\begin{thebibliography}')]
inventory = set((ROOT.parent / 'REPOSITORY_PROGRAM_PATHS.txt').read_text().splitlines())
for row in data:
    assert row['printed_path'] == row['repository_path']
    assert row['repository_path'] in inventory
    assert Path(row['repository_path']).name not in table
    content = Path(row['local_path']).read_bytes()
    assert len(content) == row['bytes']
    assert hashlib.sha256(content).hexdigest() == row['sha256']
    for path in OUT.glob('*records*II*.tsv'):
        if path.name == 'S6_SERIES_PUBLISH_records_II_additions160.tsv':
            continue
        with path.open(newline='') as f:
            for existing in csv.DictReader(f, delimiter='\t'):
                assert existing.get('sha256') != row['sha256'], (path, existing)

scopes = [
    r'Elliptic root coordinates, the integral boundary matrix, sample plurigenera and the Hopf threefold map (\cref{cdp:st:C.2.UN.6,prop:II:multiple-elliptic-hopf-threefold})',
    r'Cuspidal self-product charts, the divisor intersection matrix and cohomology arithmetic (\cref{cdp:st:C.2.UN.8})',
    r'Kummer quotient chart cocycles, quadratic generators, Gysin matrices and Euler arithmetic (\cref{cdp:st:C.2.UN.13})',
    r'Enriques filling equations, involution, quotient multiplicities and Euler arithmetic (\cref{cdp:st:C.2.UN.25})',
    r'Enriques support incidence and curve-class matrices, including the paired-root family (\cref{cdp:st:C.2.UN.25,cdp:st:C.2.UN.27})',
    r'Cyclic integral norm identities and compatible elliptic and kernel characters (\cref{cdp:st:C.2.UN.35})',
    r'Sample cusp blowup sequences, genus formulas and ruled-support Euler arithmetic (\cref{cdp:st:C.2.UN.45})',
]
details = [
    'Checks quotient substitutions and the q-action for m=2,...,12, the fixed four-by-two integral boundary matrix and its Smith form, finite pairs of plurigenera for m,n=2,...,12, and the homogeneous Hopf map equivariance/fibre description. The receiving counterexample owner is P328. No whole global construction is delegated to this finite source.',
    'Computes the factorization and all three local chart substitutions over the cubic cyclotomic field, verifies that t^6-1 has simple roots, computes the four-by-four divisor matrix determinant/rank, and evaluates the displayed support/ambient Betti and Euler arithmetic. The topological quotient and Picard arguments remain in UN8.',
    'Uses exact rational arithmetic for invariant parity lattices, nine overlap maps and their inverses/cocycles, six quadratic generators and Veronese relations, the two-form character, exterior invariants, fixed points, explicit Gysin/section and support restriction matrices, and finite Euler/cohomology arithmetic. Its JSON report is generated by this program and receives no separate appendix row. Runtime audit-plan or source-hash fields confer no current execution credit.',
    'Its complete source identifies UN25: discriminant and base involution, elliptic double cover, positive/negative root charts, the A1 equation with squared base parameter, all central multiplicities, and the Euler arithmetic before and after six negative blocks. It is not assigned to the earlier UN18 by an approximate line range.',
    'Its complete source gives the original Enriques incidence and curve-class maps, exact kernel/rank calculations, support/coherent Betti arithmetic, and a parameterized paired-root matrix routine evaluated at r=2,3,4. The actual body consumers are UN25 and UN27.',
    'Its complete source checks the integral matrices of orders 1,2,3,4,6, their exact orders/determinants/norm sums, the augmentation and induced-sign identities, the C6 restriction conjugacy, and the compatible elliptic quotient/additive-kernel eigencharacters. The actual body consumer is UN35.',
    'For g=1,...,50 computes Euclidean cusp blowup multiplicities and the delta/arithmetic-genus identity, verifies the parity and arithmetic balancing count, and evaluates the ruled Betti/Euler formulas. The general construction and its map remain in UN45.',
]
new = ''.join(scope + r' & \nolinkurl{' + row['repository_path'] + r'} \\[3pt]' + '\n'
              for scope, row in zip(scopes, data))
(OUT / 'S6_SERIES_PUBLISH_c3_provenance_program_rows160.tex').write_text(new, newline='\n')
anchor = '\\end{longtable}}\n\n\\begin{thebibliography}'
assert source.count(anchor) == 1

def write(name, rows):
    with (OUT / name).open('w', newline='') as f:
        w = csv.DictWriter(f, list(rows[0]), delimiter='\t', lineterminator='\n')
        w.writeheader()
        w.writerows(rows)

write('S6_SERIES_PUBLISH_c3_provenance_program_edits160.tsv', [dict(
    change_id='II-C3-PROV-160', type='D09',
    statement_id='cdp:st:C.2.UN.6;prop:II:multiple-elliptic-hopf-threefold;cdp:st:C.2.UN.8;cdp:st:C.2.UN.13;cdp:st:C.2.UN.25;cdp:st:C.2.UN.27;cdp:st:C.2.UN.35;cdp:st:C.2.UN.45',
    old_location='Programs: end of table', old_page='source guard; final concordance pending',
    new_location='Programs: occurrence constructions', new_page='integrated build pending',
    old_text=anchor, new_text=new + anchor,
    reason='Seven complete pinned program sources were opened and matched to the exact attached inventory. None is present under its basename or mapped source hash in the current appendix. The rows retain only their actual finite computations. Exact owner comparison assigns E_enriques_filling to UN25, A_enriques_support to UN25/UN27 and A_equivariant_torus to UN35. The UN13 JSON output is identified through its generator. Body filename removals belong to root\'s receiving units and are not performed here.',
    review_status='All seven complete sources read; paths, bytes, SHA256 and duplicate checks exposed. No program execution, full consumer-proof rereading beyond separately recorded units, or new independent computation claimed.')])
write('S6_SERIES_PUBLISH_records_II_additions160.tsv', [
    {key: row[key] for key in ['printed_path', 'repository_path', 'sha256']} for row in data])
write('S6_SERIES_PUBLISH_c3_provenance_program_checks160.tsv', [dict(
    printed_path=row['printed_path'], repository_path=row['repository_path'],
    sha256=row['sha256'], bytes=row['bytes'], checked_at=row['url'],
    mathematical_scope=scope, exact_extent=detail,
    date_utc=datetime.now(timezone.utc).isoformat(),
    outcome='Exact attached-inventory path and prescribed pinned bytes verified; complete source read; no appendix or mapped-hash duplicate; no execution.')
    for scope, detail, row in zip(scopes, details, data)])
print('Prepared addition160: seven exact program rows; shared source unchanged; no programs executed.')
