#!/usr/bin/env python3
"""Number remaining definitions and resolve local references by their retained labels."""
import re,json,csv
from S6_SERIES_PUBLISH_editing import Editor,ROOT
e=Editor('V')
# A section label must precede the numbered definition it contains.
e.replace('\\section{The boundary of the family}\n\n\\begin{definition}[Analytic extension at the parameter boundary]\\label{def:V:analytic-boundary-extension}\\label{pub:V:sec-boundary}', '\\section{The boundary of the family}\\label{pub:V:sec-boundary}\n\n\\begin{definition}[Analytic extension at the parameter boundary]\\label{def:V:analytic-boundary-extension}', 'D23','Keep the organization label attached to its section, and the definition label attached to its numbered definition.','def:V:analytic-boundary-extension')
# Canonical local data of the second construction belong to a definition.
a=e.text.index('In this section $X=X_c$ has the canonical sphere twists')
b=e.text.index('\\begin{theorem}[A smooth compact model',a)
old=e.text[a:b]
new=r'''\begin{definition}[The resolved-product datum]
\label{def:V:resolved-product-data}
Let $X$ be a canonical marked member of the $(3,4,\infty)$
family, with sphere twists
$v_1=(1,2,-4,0)^t$, $v_2=(-1,-3,3,0)^t$ and the untwisted
cusp collar. Write $S_1,S_2$ for the reduced multiple fibres,
of multiplicities three and four, and $W$ for the cusp divisor.
Orient complex manifolds by their complex structures and use
integral cohomology unless a coefficient field is specified.
Put $L=\mathcal O_X(S_1-S_2)$.
The meromorphic functions $t$, $t-1$ and their quotient give
$3S_1\sim4S_2\sim W$. Tensoring these divisor isomorphisms gives
\[
 L^3\cong\mathcal O_X(S_2),\qquad
 L^4\cong\mathcal O_X(S_1),\qquad
 L^6\cong\mathcal O_X(2S_2),\qquad
 L^{12}\cong\mathcal O_X(W).
\]
\end{definition}

'''
e.replace(old,new,'D13','Number the resolved-product datum and explicitly state the divisor isomorphisms used by its Weierstrass coefficients.','def:V:resolved-product-data')
# Put the characteristic identities immediately before their first global use.
a=e.text.index('\\section{Characteristic-number conventions}')
b=e.text.index('\\section{The monodromy and the marked cusp}',a)
chunk=e.text[a:b]
e.replace(chunk,'','D14','Move the characteristic-number input next to its first application, after the period construction.','pub:V:sec-characteristic-conventions')
marker='\\section{The integral eight-manifold}'
e.replace(marker,chunk+marker,'D14','State the characteristic input before the final integral-homology theorem that uses it.','pub:V:sec-characteristic-conventions')
# Every new numbered environment gets one permanent tag and its small printed tag.
start=e.text.index('\\begin{document}');body=e.text[start:]
pat=re.compile(r'\\begin\{(maintheorem|theorem|proposition|lemma|corollary|definition|remark)\}(?:\[([^\]]*)\])?')
newrows=[];nexttag=15
for m in list(pat.finditer(body)):
 end=body.index('\\end{'+m[1]+'}',m.start());block=body[m.start():end]
 if '\\StatementRecord' in block:continue
 labs=re.findall(r'\\label\{([^}]+)\}',block)
 if not labs:raise ValueError(('unlabelled statement',m[0]))
 label=labs[0];tags=re.findall(r'\\hypertarget\{tag-([^}]+)\}',block)
 if tags:tag=tags[0];prefix=''
 else:
  while ('tag-PV'+str(nexttag).zfill(2)) in e.text:nexttag+=1
  tag='PV'+str(nexttag).zfill(2);nexttag+=1;prefix='\\hypertarget{tag-'+tag+'}{}'
 old='\\label{'+label+'}'
 new=prefix+old+'\n\\StatementRecord{'+label+'}{proved}{'+tag+'}{}'
 e.replace(old,new,'D10','Give the numbered mathematical block its permanent small tag, with no machine metadata printed.',label)
 newrows.append({'tag':tag,'paper':'V','number':'pending build','page':'pending build','label':label,'status':'proved','kind':m[1]})
# Capitalize retained short titles consistently.
for old in set(re.findall(r'\\begin\{(?:theorem|lemma|proposition|corollary)\}\[[a-z][^\]\n]*\]',e.text)):
 new=re.sub(r'(?<=\[)[a-z]',lambda m:m[0].upper(),old,count=1)
 e.replace(old,new,'D16','Capitalize the short mathematical statement title.',count=e.text.count(old))
# Replace the production-level proof-rung numbering by ordinary numbered steps.
old=r'label={$\langle1\rangle$\arabic*.}'
if old in e.text:e.replace(old,r'label=\arabic*.','D10','Use ordinary proof-step numbers in place of the inherited proof-rung marker.',count=e.text.count(old))
# Current local references are generated by cleveref; cross-paper references remain for final series regeneration.
a=e.text.index('\\begin{document}');head=e.text[:a];body=e.text[a:];locals=set(re.findall(r'\\label\{([^}]+)\}',body))
replacements=[]
pat=re.compile(r'(?:(Theorem|Proposition|Lemma|Corollary|Definition|Remark|Equation|equation)\s+)?\\SeriesRef\{([^}]+)\}')
def change(m):
 if m[2] not in locals:return m[0]
 macro='\\Cref' if m[1] and m[1][0].isupper() else '\\cref'
 replacement=macro+'{'+m[2]+'}'
 replacements.append({'old':m[0],'new':replacement,'label':m[2]});return replacement
new=pat.sub(change,body)
for r in replacements:e.record('D04',r['old'],r['new'],'Resolve the local number and statement kind from the retained label, not an old fixed series number.',r['label'])
e.text=head+new
if '\\crefname{maintheorem}' not in e.text:
 e.replace('\\renewcommand{\\themaintheorem}{\\Alph{maintheorem}}','\\renewcommand{\\themaintheorem}{\\Alph{maintheorem}}\n\\crefname{maintheorem}{theorem}{theorems}','D23','Give main theorems their proper cleveref type.')
# Stable outline anchors have new displayed theorem letters.
for oldid in 'ABCDEF':
 pat=re.compile(r'(\\expandafter\\def\\csname SBack@[^\n]+)(?=\n)')
 for m in list(pat.finditer(e.text)):
  old=m[0];needle='Theorem '+oldid
  if needle in old:
   e.replace(old,old.replace(needle,'Theorem~\\ref*{series:V:'+oldid+'}'),'D24','Regenerate retained metadata back-link letters from the stable main-theorem label.')
e.save()
# Preserve the entire original tag registry; append only newly created tags.
p=ROOT/'S6_SERIES_PUBLISH_tags.tsv'
with p.open() as f:rows=list(csv.DictReader(f,delimiter='\t'));fields=list(rows[0])
bylabel={x['label'] for x in rows};bytag={x['tag'] for x in rows}
for r in newrows:
 if r['label'] not in bylabel:
  assert r['tag'] not in bytag,r
  rows.append(r);bylabel.add(r['label']);bytag.add(r['tag'])
# Include every other new PV-tagged primary statement introduced earlier.
s=e.text[e.text.index('\\begin{document}'):]
for m in re.finditer(r'\\hypertarget\{tag-(PV\d+)\}\{\}\\label\{([^}]+)\}',s):
 if m[2] not in bylabel:
  assert m[1] not in bytag
  rows.append({'tag':m[1],'paper':'V','number':'pending build','page':'pending build','label':m[2],'status':'proved','kind':'statement'});bylabel.add(m[2]);bytag.add(m[1])
with p.open('w') as f:w=csv.DictWriter(f,fieldnames=fields,delimiter='\t');w.writeheader();w.writerows(rows)
(ROOT/'records/S6_SERIES_PUBLISH_V_new_statement_tags.json').write_text(json.dumps(newrows,indent=2)+'\n')
print('local references',len(replacements),'new tag headers',len(newrows))
