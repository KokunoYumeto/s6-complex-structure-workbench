"""Exact CM-projected tensor comparison; no arithmetic descent is assumed."""
from pathlib import Path
import sympy as S,itertools,json,hashlib
b,w,t,u,d,v,s=S.symbols('beta omega t u D v s',nonzero=True)
mod=b*b+19
def red(x):
 n,q=S.fraction(S.cancel(x));n=S.rem(n,mod,b);q=S.rem(q,mod,b)
 a=q.coeff(b,0);c=q.coeff(b,1)
 return S.factor(S.cancel(S.rem(S.expand(n*(a-c*b)),mod,b)/(a*a+19*c*c)))
def R(M):return M.applyfunc(red)
def ser(M):return [[str(x)for x in row]for row in M.tolist()]
checks=[]
def ck(name,M,N=0):
 if isinstance(M,S.MatrixBase):
  if N==0:N=S.zeros(*M.shape)
  ok=R(M-N)==S.zeros(*M.shape)
 else:ok=red(M-N)==0
 assert ok,name;checks.append(name)
tau=(19+b)/38;taub=(19-b)/38;q=-b*t/w
E=S.Matrix([[w,tau*w],[q,taub*q]])
JB=S.Matrix([[-19,-10],[38,19]]);JD=S.diag(b,-b)
ck('CM square Betti',JB*JB,-19*S.eye(2));ck('CM square deRham',JD*JD,-19*S.eye(2))
ck('CM comparison',E*JB,JD*E);ck('Legendre determinant',E.det(),-t)
P=S.Matrix([[t,d*w-q*u,d*tau*w-taub*q*u,v],[0,w,tau*w,u],[0,q,taub*q,d],[0,0,0,1]])
pairs=list(itertools.combinations(range(4),2))
C=S.Matrix([[P.extract(I,J).det()for J in pairs]for I in pairs])
BB=S.zeros(6,5);BD=S.zeros(6,5)
for row,col in [(0,0),(1,1),(4,3),(5,4)]:BB[row,col]=BD[row,col]=1
BB[2,2]=1;BB[3,2]=-1;BD[2,2]=BD[3,2]=1
C5=R((C*BB).extract([0,1,2,4,5],range(5)))
ck('primitive full comparison',C*BB,BD*C5)
K=R(S.kronecker_product(C5,E.inv().T))
embB=S.Matrix([[1,-19],[0,-10],[0,38],[1,19]])
embD=S.Matrix([[1,b],[0,0],[0,0],[1,-b]])
piB=S.Matrix([[S.Rational(1,2),0,0,S.Rational(1,2)],[S.Rational(1,2),-1,S.Rational(5,19),-S.Rational(1,2)]])
piD=S.Matrix([[S.Rational(1,2),0,0,S.Rational(1,2)],[-b/38,0,0,b/38]])
ck('Betti retraction',piB*embB,S.eye(2));ck('deRham retraction',piD*embD,S.eye(2))
Ad=R(S.kronecker_product(E,E.inv().T));ck('CM endomorphism transport',Ad*embB,embD)
ck('CM quotient transport',piD*Ad,piB)
include=S.diag(embB,S.eye(2),embB);project=S.diag(piD,S.eye(2),piD)
N=R(project*K*include)
ck('bottom Tate block',N[:2,:2],t*S.eye(2));ck('top lattice block',N[4:6,4:6],S.eye(2))
ck('middle polarization block',N[2:4,2:4],t*E.inv().T)
# The actual central coordinate survives; its precise derivative is recorded.
central=R(N.diff(v));ck('nonzero central rank',central.rank(),2)
# Compute the original compactness expression in the CM-period basis.
minor=R(C5)[0,3];ck('compact minor is retained in primitive tensor source',minor,u*(d*w-q*u)-w*v)
center=R(N[:2,4:6]); central_change=R(center.subs(v,v+t*s)-center)
# A rational middle reindex identifies t*E^{-t} with E.
J=S.Matrix([[0,1],[-1,0]])
ck('middle actual polarization arrow',J*(t*E.inv().T)*J,E)
L=S.diag(S.eye(2),J,S.eye(2));RR=S.diag(S.eye(2),J,S.eye(2));NN=R(L*N*RR)
ck('middle elliptic block after exact basis maps',NN[2:4,2:4],E)
# Identify the projected object with the actual enlarged group and two points.
a=S.symbols('a_CM')
LF=S.eye(6);LF[1,1]=-19;LF[1,2]=a;LF[3,5]=a
RF=S.eye(6);RF[1,1]=-S.Rational(1,19)
Final=R(LF*NN*RF)
k=S.Matrix([[d*w-q*u,d*tau*w-taub*q*u]])
kbeta=S.Matrix([[(-b*d+a)*w-q*b*u,(-b*d+a)*tau*w-taub*q*b*u]])
v2=-b*u*d+a*u
expected=S.zeros(6)
expected[0,0]=expected[1,1]=t
expected[0,2:4]=k;expected[1,2:4]=kbeta
expected[2:4,2:4]=E
expected[0,4]=-v;expected[0,5]=b*u*d
expected[1,4]=-v2;expected[1,5]=19*v+b*a*u
expected[2:4,4:6]=S.Matrix([[-u,b*u],[-d,-b*d+a]])
expected[4:6,4:6]=S.eye(2)
ck('full projected object actual enlarged-group period matrix',Final,expected)
ck('actual deRham change determinant',LF.det(),-19)
ck('actual Betti change determinant',RF.det(),-S.Rational(1,19))
U=S.Matrix([u,v,v2]);dB=S.Matrix([[b,0,0],[a,0,-1],[b*a,19,0]])
ck('first lattice generator is negative actual compact logarithm',Final.extract([2,0,1],[4]),-U)
ck('second lattice generator is the actual B image',Final.extract([2,0,1],[5]),dB*U)
# Track the original tested entry through the top CM projection.
full_test=red(-K[0,7]/b)
projected_test=red((N[0,5]+b*N[1,5])/b)
ck('full normalized original compact minor',full_test,minor/w)
ck('projected tested entry',projected_test,u*d-v)
ck('precise discarded Gaussian term',full_test-projected_test,b*t*u*u/(w*w))
A12=S.Matrix([0,1,0,0]);lost=A12-embB*piB*A12
ck('discarded top component lies in kernel',piB*lost)
ck('discarded top component nonzero first coordinate',lost[0],-19)
# Check the actual CM projector and carried Hodge filtration, not just weights.
for j in range(4):
 ej=S.eye(4)[:,j];Aj=S.Matrix(2,2,list(ej));pj=R((Aj-JB*Aj*JB/19)/2)
 ck('Betti CM projector matrix unit '+str(j),embB*piB*ej,S.Matrix(list(pj)))
# In the primitive tensor de Rham basis the F degrees are
# (-1,-2,0,-1,0,-1,0,-1,1,0). The top CM subobject
# has F0 generated by bottom e2, middle e4, and top I,J_D.
F0pre=S.zeros(10,4);F0pre[2,0]=1;F0pre[4,1]=1
F0pre[6:10,2:4]=embD
F0quot=R(project*F0pre)
ck('quotient F0 rank',F0quot.rank(),3)
ck('quotient F0 outside allowed coordinates',F0quot.extract([0,1,3],range(4)))
F0actual=R(LF*L*F0quot)
ck('actual motive F0 rank',F0actual.rank(),3)
ck('actual motive F0 is kernel of Lie G projection',F0actual.extract([0,1,2],range(4)))
