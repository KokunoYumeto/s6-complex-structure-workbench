checks=[]
def ck(name, cond):
    if not cond: raise AssertionError(name)
    checks.append(name)
def rank(a):
    if not a:return 0
    a=[[F(x) for x in r] for r in a];n=len(a[0]);i=0
    for j in range(n):
        k=next((k for k in range(i,len(a)) if a[k][j]),None)
        if k is None:continue
        a[i],a[k]=a[k],a[i];d=a[i][j];a[i]=[x/d for x in a[i]]
        for k in range(len(a)):
            if k!=i and a[k][j]:
                d=a[k][j];a[k]=[x-d*y for x,y in zip(a[k],a[i])]
        i+=1
        if i==len(a):break
    return i
def diag(vals):return [[v if i==j else 0 for j in range(len(vals))] for i,v in enumerate(vals)]
def add(a,b):return tuple(x+y for x,y in zip(a,b))
def multsub(exponents, substitutions):
    return tuple(sum(e*s[k] for e,s in zip(exponents,substitutions)) for k in range(len(substitutions[0])))
def euler(b):return sum((-1)**k*x for k,x in enumerate(b))
def polytrim(a):
    while a and a[-1]==0:a.pop()
    return a
def rem(a,b):
    a=list(map(F,a));b=polytrim(list(map(F,b)))
    while len(a)>=len(b):
        d=a[-1]/b[-1];s=len(a)-len(b)
        for i,x in enumerate(b):a[i+s]-=d*x
        polytrim(a)
    return a
def gcd(a,b):
    a=polytrim(list(map(F,a)));b=polytrim(list(map(F,b)))
    while b:a,b=b,rem(a,b)
    return [x/a[-1] for x in a]

# Construct all exterior generators before taking the invariant projector.
quot=[0]*7
for k in range(5):
    basis=list(combinations(range(4),k));sgn=(-1)**k
    pr=diag([F(1+sgn,2)]*len(basis))
    for l in (0,2):quot[k+l]+=rank(pr)
ck('finite-quotient invariant cohomology via exact projector',quot==[1,0,7,0,7,0,1])
coh=[]
for k in range(4):
    b=list(combinations(range(2),k)) if k<=2 else []
    coh.append(rank(diag([F(1+(-1)**k,2)]*len(b))))
