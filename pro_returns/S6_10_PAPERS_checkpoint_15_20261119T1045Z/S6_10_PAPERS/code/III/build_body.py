def tex(s):
    return s.replace('\\','\\textbackslash{}').replace('&',r'\&').replace('%',r'\%').replace('#',r'\#').replace('_',r'\_')


def numbered(proof):
    """Number the exact original prose paragraphs, retaining displays with prose."""
    if re.search(r'\\begin\{enumerate\}|\\item\b',proof):
        return proof
    pieces=re.split(r'\n[ \t]*\n+',proof.strip())
    groups=[]
    pending=''
    for piece in pieces:
        piece=piece.strip()
        if not piece: continue
        if piece.startswith((r'\[',r'\begin{equation}',r'\begin{align}',r'\begin{gather}',r'\begin{array}',r'\begin{center}',r'\begin{tabular}')) and groups:
            groups[-1]+='\n\n'+piece
        else:
            groups.append(piece)
    if len(groups)==1:
        return '\\begin{enumerate}[label=\\arabic*.,leftmargin=*]\n\\item '+groups[0]+'\n\\end{enumerate}'
    # A group containing an open display/environment is joined to following
    # groups before any list marker is inserted.
    joined=[];buffer=''
    for group in groups:
        buffer += ('\n\n' if buffer else '') + group
        opened=len(re.findall(r'\\begin\{',buffer))-len(re.findall(r'\\end\{',buffer))
        displays=buffer.count(r'\[')-buffer.count(r'\]')
        if opened==0 and displays==0:
            joined.append(buffer);buffer=''
    if buffer: joined.append(buffer)
    return '\\begin{enumerate}[label=\\arabic*.,leftmargin=*]\n'+ '\n\n'.join('\\item '+g for g in joined)+'\n\\end{enumerate}'


def history(label,history_map):
    vals=history_map.get(label,[])
    names=[]
    for val in vals:
        for rec in val.get('named_historical_checks',[]):
            prefix='Source reading by ' if rec.get('record_kind')=='source reading' else ''
            name=prefix+rec['who']+((', effort '+rec['effort']) if rec.get('effort') else '')+((', '+rec['date']) if rec.get('date') else '')
            if name not in names:names.append(name)
    return '; '.join(names) if names else 'Historical source production record retained in the inventory'


