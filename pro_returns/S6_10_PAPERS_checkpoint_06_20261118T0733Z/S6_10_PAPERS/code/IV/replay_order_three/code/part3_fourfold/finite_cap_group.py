#!/usr/bin/env python3
"""Retain the finite kernel and marked meridians of each affine root cap."""
from pathlib import Path
from math import gcd
import json
import sympy as s

rows=[]
for m in range(1,25):
    for n in range(-2*m,2*m+1):
        g=gcd(m,n);mp=m//g;np=n//g
        r,ss,d=s.gcdex(np,mp)
        r,ss,d=int(r),int(ss),int(d)
        assert d==1 and r*np+ss*mp==1
        C=s.Matrix([mp,-np]);H=s.Matrix([r,ss])
        P=s.Matrix.hstack(C,H)
        assert P.det()==1
        relation=s.Matrix([m,-n])
        assert P.inv()*relation==s.Matrix([g,0])
        assert s.Matrix([1,0])==ss*C+np*H
        assert s.Matrix([0,1])==-r*C+mp*H
        exponent=s.Rational(n,m)*r+ss
        assert exponent==s.Rational(1,mp)
        rows.append({'m':m,'n':n,'g':g,'primitive_m':mp,'primitive_n':np,
                     'bezout':[r,ss],
                     'kernel_generator_A_B':[mp,-np],
                     'new_basis_C_H':[[int(v) for v in P.row(i)] for i in range(2)],
                     'relation_in_C_H':[g,0],
                     'A_in_C_H':[ss,np],'B_in_C_H':[-r,mp],
                     'contracting_scalar_exponent':str(exponent)})
data={'proof':'notes/part3_log_caps.md P3K.15',
      'group':'<A,B | AB=BA, A^m=B^n>',
      'exact_decomposition':'Z/(gcd(m,n)) generated by C, plus Z generated by H',
      'marked_meridians_retained':'A=C^s H^(n/g), B=C^(-r) H^(m/g)',
      'local_orbit':'Mapping torus of the actual source map of H after the finite C quotient',
      'cases':rows}
Path(__file__).with_suffix('.json').write_text(json.dumps(data,indent=2)+'\n')
print('PASS:',len(rows),'integer cap decompositions, with every basis matrix unimodular.')
print('Finite kernel, both marked meridians, and the positive residual scalar exponent retained exactly.')
