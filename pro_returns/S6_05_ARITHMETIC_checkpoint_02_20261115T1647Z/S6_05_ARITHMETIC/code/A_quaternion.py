"""Exact order, adjoint, and double-coset algebra used in Part A."""
from fractions import Fraction as F
import sympy as S
from itertools import product

def mul(x,y):
    a,b,c,d=x; e,f,g,h=y
    return S.Matrix([a*e+3*b*f-c*g+3*d*h,
        a*f+b*e+c*h-d*g,
        a*g+c*e+3*b*h-3*d*f,
        a*h+d*e+b*g-c*f])
def bar(x):return S.Matrix([x[0],-x[1],-x[2],-x[3]])
def nr(x):return S.expand(mul(x,bar(x))[0])
one=S.Matrix([1,0,0,0]); i=S.Matrix([0,1,0,0]); j=S.Matrix([0,0,1,0]); k=S.Matrix([0,0,0,1])
w=(one+i+j+k)/2
basis=S.Matrix.hstack(one,i,j,w)
print('Maximal order basis (columns):',basis)
for r in range(4):
 for s in range(4):
  c=basis.inv()*mul(basis[:,r],basis[:,s]); assert all(x.q==1 for x in c)
print('multiplication integral PASS')
tr=S.Matrix(4,4,lambda r,s:2*mul(basis[:,r],basis[:,s])[0]);print('trace pairing=',tr,'det=',tr.det(),'reduced discriminant=',S.sqrt(abs(tr.det())))
pi=one+j
print('pi norm=',nr(pi),'pi i pi^-1=',mul(mul(pi,i),bar(pi))/2)
print('pi normalizes maximal order:')
for r in range(4):
 c=basis.inv()*mul(mul(pi,basis[:,r]),bar(pi))/2
 print(tuple(c));assert all(x.q==1 for x in c)
I=3*i+3*j; J=i+3*j; K=mul(I,J)
assert mul(I,I)==18*one and mul(J,J)==-6*one and mul(I,J)==-mul(J,I)
print('old I,J,K:',tuple(I),tuple(J),tuple(K))
old=S.Matrix.hstack(one,(I+J)/2,(I-J)/2,K/2)
print('old order in new basis:',old,'index in maximal=',abs((basis.inv()*old).det()))
r,s,t,u=S.symbols('r s t u',integer=True)
g=r*one+s*i+3*t*j+3*u*k
V=S.Matrix.hstack((i+3*j)/2, (3*i+3*j)/2,3*k)
# full pure coordinate basis has rank3; drop scalar row
Adj=S.Matrix.hstack(*[mul(mul(g,V[:,b]),bar(g)) for b in range(3)])
Adj=S.simplify(V[1:4,:].inv()*Adj[1:4,:])
print('adjoint in (a,q,n):',Adj)
assert all(S.Poly(x,r,s,t,u).domain==S.ZZ for x in Adj)
print('integral adjoint on full Z^3 PASS')
G=S.diag(1,-3,-18)
assert S.simplify(Adj.T*G*Adj-nr(g)**2*G)==S.zeros(3)
print('preserves F when norm(g)=1 PASS')
print('norm(g)=',nr(g))
M=S.Matrix([[17,0,72],[0,1,0],[4,0,17]])
assert M.det()==1 and M.T*G*M==G
print('height map determinant and isometry PASS')
# Counterexample to universal positive-norm ideal-generator assertion.
assert all((a*a-3*b*b-2)%3 for a,b in product(range(3),repeat=2))
print('norm 2 generator impossible mod 3; ideal (1+sqrt3) norm 2 PASS')
# Action of some maximal-order units on the larger diagonal lattice.
for name,g0 in [('j',j),('elliptic3',(one+i+3*j+k)/2),('eps',2*one+i),('spin6',3*one+k)]:
 AA=S.Matrix.hstack(*[mul(mul(g0,V[:,b]),bar(g0))/nr(g0) for b in range(3)])
 AA=S.simplify(V[1:4,:].inv()*AA[1:4,:]);print(name,'norm',nr(g0),'adjoint',AA,'integral',all(x.q==1 for x in AA))
 print('normalizes old order',all(x.q==1 for x in old.inv()*S.Matrix.hstack(*[mul(mul(g0,old[:,b]),bar(g0))/nr(g0) for b in range(4)])))

# The complete finite norm-one group at the ramified prime 3.
def mm3(x,y): return tuple(int(v)%3 for v in mul(x,y))
units3={x for x in product(range(3),repeat=4) if int(nr(x))%3==1}
gens3=[(0,0,1,0),(2,1,0,0),(2,0,0,1)]
closure={(1,0,0,0)}
todo=list(closure)
while todo:
 x=todo.pop()
 for g in gens3:
  y=mm3(x,g)
  if y not in closure: closure.add(y);todo.append(y)
old3={x for x in units3 if x[2]==x[3]==0}
assert closure==units3 and len(units3)==36 and len(old3)==6
print('modulo 3: norm-one group order',len(units3),'generated by reductions of j,2+i,2+k')
print('old-order subgroup order',len(old3),'index',len(units3)//len(old3),'PASS')
