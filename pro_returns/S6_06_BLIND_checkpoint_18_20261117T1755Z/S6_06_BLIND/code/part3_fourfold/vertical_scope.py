#!/usr/bin/env python3
"""Exact retained-component pairings and cyclic double-curve characters."""
from pathlib import Path
from math import gcd
from functools import reduce
import json
import sympy as s
from sympy.matrices.normalforms import smith_normal_form
from sympy.polys.matrices import DomainMatrix
from sympy.polys.matrices.normalforms import smith_normal_decomp

def cycle(n):
    if n==1:return s.zeros(1)
    B=s.zeros(n)
    for i in range(n):
        j=(i+1)%n
        B[i,i]-=1;B[j,j]-=1
        B[i,j]+=1;B[j,i]+=1
    return B

def ints(M):return [[int(v) for v in M.row(i)] for i in range(M.rows)]
rows=[]
for n in range(2,13):
    B=cycle(n)
    for c in range(n):
        g=gcd(n,c);h=n//g
        Z=s.zeros(n,g)
        for j in range(n):Z[j,j%g]=1
        P=s.zeros(n)
        for j in range(n):P[(j+c)%n,j]=1
        assert P*Z==Z
        gram=Z.T*B*Z
        assert gram==h*cycle(g)
        assert gram.rank()==g-1
        # A vertical correction D makes the multidegree Q-invariant
        # precisely when (1-P)(e_j-e_0+B D)=0.
        E=(s.eye(n)-P)*B
        dm,um,vm=smith_normal_decomp(DomainMatrix.from_Matrix(E).convert_to(s.ZZ))
        dm,um,vm=[A.to_Matrix() for A in (dm,um,vm)]
        possible=[]
        for j in range(n):
            source=s.zeros(n,1);source[j,0]+=1;source[0,0]-=1
            rhs=-(s.eye(n)-P)*source
            z=um*rhs;rank=E.rank()
            solvable=all(z[i,0]%dm[i,i]==0 for i in range(rank)) and all(z[i,0]==0 for i in range(rank,n))
            assert solvable==(j%h==0)
            if solvable:possible.append(j)
        rows.append({'n':n,'translation_component':c,'orbits':g,'orbit_length':h,
          'surface_intersection':ints(B),'orbit_sum_columns':ints(Z),
          'orbit_intersection':ints(gram),'rank':g-1,
          'orbit_smith':ints(smith_normal_form(gram,domain=s.ZZ)),
          'allowed_generic_Picard_components':possible})

characters=[]
for h in range(2,33):
    for e in range(1,h):
        for b in range(h):
            c=(1-b)%h
            refl=[j for j in range(1,h) if sum((j*w)%h!=0 for w in (e,b,c))==1]
            assert all((j*e)%h==0 for j in refl)
            step=reduce(gcd,[h]+refl)
            assert step>1
            characters.append({'h':h,'elliptic_weight':e,'x_weight':b,'y_weight':c,
                               'pseudoreflection_exponents':refl,'generated_step':step})

data={'proof':'notes/part3_vertical_scope.md',
 'retained_component_cycles':rows,
 'symbolic_rule':'For g=gcd(n,c), orbit Gram=(n/g)*cycle(g), rank g-1.',
 'vertical_integrality_rule':'An invariant multidegree extension exists exactly when (n/g) divides the generic Picard component.',
 'cyclic_double_curve_checks':characters,
 'character_rule':'b+c=1 mod h; every pseudoreflection acts trivially on the elliptic tangent; a nontrivial elliptic action cannot be generated by them.'}
Path(__file__).with_suffix('.json').write_text(json.dumps(data,indent=2)+'\n')
print('Verified',len(rows),'retained I_n component-orbit intersection matrices and full integer extension tests.')
print('Verified',len(characters),'cyclic character triples with faithful z=xy base character, h<=32.')
print('General proofs, including the actual cycle morphisms and the analytic quotient comparison, are retained in the accompanying note.')
