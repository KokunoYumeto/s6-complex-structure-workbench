#!/usr/bin/env python3
"""Typeset the executed exact Part 4 integer maps without eliding entries."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
matrices = json.loads((HERE / 'example_matrices.json').read_text())
names = {
    'local_d1': r'\partial_1', 'local_d2': r'\partial_2',
    'local_d3': r'\partial_3', 'local_d4': r'\partial_4',
    'MV_F0': 'F_0', 'MV_F1': 'F_1', 'MV_F2': 'F_2',
    'H1_reduced_relation_matrix': r'R_{H_1}',
    'H2_reduced_relation_matrix': r'R_{H_2}',
}
for i in range(1, 4):
    names[f'S_{i}'] = f'S_{i}'
    names[f'R1_{i}'] = f'R_{{1,{i}}}'
    names[f'R2_{i}'] = f'R_{{2,{i}}}'

order = [f'S_{i}' for i in range(1,4)]
order += [f'R1_{i}' for i in range(1,4)] + [f'R2_{i}' for i in range(1,4)]
order += [f'local_d{i}' for i in range(1,5)]
order += ['MV_F0','MV_F1','MV_F2','H1_reduced_relation_matrix','H2_reduced_relation_matrix']
out = ['% Generated by code/part4/matrices_to_tex.py from example_matrices.json.',
       r'\begingroup', r'\setlength{\arraycolsep}{1.7pt}', r'\renewcommand{\arraystretch}{0.88}']
for key in order:
    A = matrices[key]
    n, m = len(A), len(A[0])
    assert all(len(row) == m for row in A)
    assert all(isinstance(x, int) for row in A for x in row)
    out += [r'\par\smallskip\noindent',
            rf'${names[key]}$ has size ${n}\times {m}$; its full integer matrix is',
            r'\[', r'\resizebox{\minof{\linewidth}{\width}}{!}{$\displaystyle ' + names[key] + r'=\begin{pmatrix}']
    out += [' & '.join(str(x) for x in row) + r'\\' for row in A]
    out += [r'\end{pmatrix}$}', r'\]']
out += [r'\endgroup', '']
# Avoid dependence on calc's minof: every matrix fits at scriptsize, while
# the two larger maps use a width-limited graphic box.
text = '\n'.join(out)
text = text.replace(r'\resizebox{\minof{\linewidth}{\width}}{!}{$\displaystyle ',
                    r'\resizebox{0.94\linewidth}{!}{$\displaystyle ')
# Small matrices should retain ordinary readable scale.
for key in order:
    if len(matrices[key][0]) <= 7:
        text = text.replace(r'\resizebox{0.94\linewidth}{!}{$\displaystyle '+names[key]+r'=\begin{pmatrix}',
                            r'\resizebox{!}{'+str(2.8*len(matrices[key]))+r'mm}{$\displaystyle '+names[key]+r'=\begin{pmatrix}')
(HERE / 'all_matrices.tex').write_text(text)
print('Wrote all_matrices.tex with', len(order), 'complete integer matrices.')
print('Largest maps:', len(matrices['MV_F1']), 'x', len(matrices['MV_F1'][0]),
      'and', len(matrices['MV_F2']), 'x', len(matrices['MV_F2'][0]))
