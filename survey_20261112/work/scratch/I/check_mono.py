import sympy as sp
T1=sp.Matrix([[1,0,-6,2],[0,-1,1,1],[0,-1,0,1],[0,0,0,1]])
T2=sp.Matrix([[1,6,0,-3],[0,0,-1,1],[0,1,0,0],[0,0,0,1]])
A1=sp.Matrix([[1,0,0,0],[6,0,1,0],[-6,-1,-1,0],[-2,1,0,1]])
A2=sp.Matrix([[1,0,0,0],[0,0,-1,0],[-6,1,0,0],[3,0,1,1]])
I=sp.eye(4)
print('orders', T1**3==I, T2**4==I, A1**3==I, A2**4==I)
print('A_j = (T_j^-1)^T', A1==(T1.inv()).T, A2==(T2.inv()).T)
print('T0=(T1T2)^-1', (T1*T2).inv())
print('M0=(A1A2)^-1', (A1*A2).inv())
# invariant Hermitian forms: H = S + i*Aalt, S real symmetric, Aalt real antisymmetric; T real => conditions separate
s=sp.symbols('s0:10'); a=sp.symbols('a0:6')
S=sp.Matrix(4,4,lambda i,j: s[[0,1,2,3,1,4,5,6,2,5,7,8,3,6,8,9][4*i+j]])
idx={(0,1):0,(0,2):1,(0,3):2,(1,2):3,(1,3):4,(2,3):5}
Aa=sp.Matrix(4,4,lambda i,j: 0 if i==j else (a[idx[(i,j)]] if i<j else -a[idx[(j,i)]]))
eqs=[]
for T in (T1,T2):
    eqs+=list(T.T*S*T-S)+list(T.T*Aa*T-Aa)
sol=sp.solve(eqs,list(s)+list(a),dict=True)[0]
print('invariant symmetric', S.subs(sol)); print('invariant alternating', Aa.subs(sol))
# commutant of A1,A2
c=sp.symbols('c0:16'); C=sp.Matrix(4,4,c)
sol2=sp.solve(list(C*A1-A1*C)+list(C*A2-A2*C),c,dict=True)[0]
print('commutant', C.subs(sol2))
# commuting quotient: submodule generated by image of commutator under the group
D=T1*T2-T2*T1
gens=[D[:,j] for j in range(4)]
M=sp.Matrix.hstack(*gens)
for _ in range(4):
    M=sp.Matrix.hstack(M,T1*M,T2*M)
# Smith normal form of lattice generated by columns
from sympy.matrices.normalforms import smith_normal_form
cols=[M[:,j] for j in range(M.shape[1])]
# reduce: take column-space lattice basis via HNF of integer matrix
from sympy.polys.matrices import DomainMatrix
from sympy import ZZ
dm=DomainMatrix.from_Matrix(M).convert_to(ZZ)
print('SNF diag of relation lattice', smith_normal_form(M[:, :12], domain=ZZ).diagonal() if M.shape[1]>=12 else None)
# period-plane restriction
mu,tau,beta=sp.symbols('mu tau beta')
aa,bb=sp.symbols('a b',real=True)
H=sp.Matrix([[0,0,0,sp.I*aa],[0,0,6*sp.I*aa,0],[0,-6*sp.I*aa,0,0],[-sp.I*aa,0,0,bb]])
print('H invariant', sp.simplify(T1.T*H*T1-H)==sp.zeros(4), sp.simplify(T2.T*H*T2-H)==sp.zeros(4), 'det', sp.factor(H.det()))
m1,m2,t1,t2,b1,b2=sp.symbols('m1 m2 t1 t2 b1 b2',real=True)
MU=m1+sp.I*m2; TAU=t1+sp.I*t2; BETA=b1+sp.I*b2
J=sp.Matrix([[6*MU,BETA],[TAU,MU],[1,0],[0,1]])
G=sp.simplify(J.H*H*J)
print('Gram', sp.simplify(G))
